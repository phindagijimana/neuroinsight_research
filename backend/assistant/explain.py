"""Plain-language explanations built from the plugin/workflow YAML.

Everything here comes from the registry definitions and a short glossary;
nothing is generated by a model.
"""
from __future__ import annotations

from typing import Any, Dict, List, Optional

GLOSSARY = {
    "T1w": "T1-weighted MRI: the standard anatomical scan, bright white matter and dark fluid.",
    "BIDS": "Brain Imaging Data Structure: a folder and filename convention, e.g. sub-01/anat/sub-01_T1w.nii.gz.",
    "space": "The coordinate frame an image lives in, e.g. the subject's own scanner space or a template like MNI.",
    "atlas": "A set of named brain regions. DKT (Desikan-Killiany-Tourville) is what FastSurfer writes.",
    "segmentation": "Labelling every voxel with a tissue type or brain region.",
    "parcellation": "Splitting the cortex into named regions from an atlas.",
    "SciCap": "Checks that your scan's metadata (modality, space, atlas) fits what the pipeline expects: ALLOW, REJECT, or ABSTAIN.",
    "SciGuard": "Checks spatial steps between images (e.g. labels moved into diffusion space need a transform): PASS, FAIL, UNKNOWN.",
    "ABSTAIN": "Not enough metadata to decide. Fill the missing field and re-check.",
    "REJECT": "The metadata contradicts what the pipeline needs. Fix the input or pick another pipeline.",
    "QC": "Quality control: looking at the outputs. A job that finishes is not automatically correct.",
}


def _params(defn: Any) -> List[Dict[str, Any]]:
    out = []
    for p in getattr(defn, "parameters", []) or []:
        out.append({
            "name": p.get("name"),
            "type": p.get("type"),
            "default": p.get("default"),
            "description": p.get("description", ""),
        })
    return out


def _inputs(items: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    return [
        {"key": i.get("key") or i.get("id"), "type": i.get("type"), "description": i.get("description", "")}
        for i in items or []
    ]


def explain_target(registry: Any, target_type: str, target_id: str, needs_fs_license: bool = False) -> Optional[Dict[str, Any]]:
    if target_type == "workflow":
        defn = registry.get_workflow(target_id)
        if not defn:
            return None
        steps = [{"id": s.id, "uses": s.uses, "label": s.label} for s in defn.steps]
    else:
        defn = registry.get_plugin(target_id)
        if not defn:
            return None
        steps = []

    input_format = getattr(defn, "input_format", {}) or {}
    profiles = getattr(defn, "resource_profiles", {}) or {}
    raw = getattr(defn, "raw_yaml", {}) or {}
    terms = [t for t in GLOSSARY if t.lower() in (defn.description or "").lower()]
    for always in ("SciCap", "QC"):
        if always not in terms:
            terms.append(always)

    return {
        "target_type": target_type,
        "target_id": target_id,
        "name": defn.name,
        "domain": defn.domain,
        "what_it_does": " ".join((defn.description or "").split()),
        "inputs_required": _inputs(defn.inputs_required),
        "input_notes": input_format.get("notes", []),
        "example_structure": input_format.get("example_structure", ""),
        "parameters": _params(defn),
        "steps": steps,
        "resources": profiles.get("default") or (raw.get("resources") or {}),
        "needs_freesurfer_license": needs_fs_license,
        "references": list(getattr(defn, "references", []) or []),
        "glossary": {t: GLOSSARY[t] for t in terms},
    }
